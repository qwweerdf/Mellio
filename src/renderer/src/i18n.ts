export function localizeError(lang: Lang, message: string): string {
  if (lang === 'zh') return message
  if (ERROR_EN[message]) return ERROR_EN[message]

  let match = message.match(/^连接成功 · (\d+) 个模型$/)
  if (match) return `Connected · ${match[1]} models`
  match = message.match(/^拉取模型失败：HTTP (\d+)(.*)$/)
  if (match) return `Failed to fetch models: HTTP ${match[1]}${match[2]}`
  match = message.match(/^服务商返回 HTTP (\d+)(.*)$/)
  if (match) return `Provider returned HTTP ${match[1]}${match[2]}`
  match = message.match(/^连接失败：HTTP (\d+)(.*)$/)
  if (match) return `Connection failed: HTTP ${match[1]}${match[2]}`
  if (message === '演示模式可用') return 'Demo mode available'

  return message
}
